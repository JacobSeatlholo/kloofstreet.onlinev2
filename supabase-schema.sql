-- Members. One row per auth.users signup. The frontend creates this row
-- itself right after auth.signUp() (id = the new user's id).
CREATE TABLE IF NOT EXISTS public.profiles (
  id            uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name  text,
  phone         text,
  status        text NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending','active','suspended')),
  points        integer NOT NULL DEFAULT 0,
  total_scans   integer NOT NULL DEFAULT 0,
  month_streak  integer NOT NULL DEFAULT 0,
  referral_code text UNIQUE,
  wallet_serial text,
  invoice_url   text,
  paid_at       timestamptz,
  activated_at  timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- Kloof Street businesses. Merchant logins are matched by login_email
-- (see the register-store SQL at the bottom of this file).
CREATE TABLE IF NOT EXISTS public.partners (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text NOT NULL,
  short_name  text,
  category    text,
  area        text,
  suburb      text,
  login_email text,
  active      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- One row per member check-in (QR scan or merchant manual check-in).
CREATE TABLE IF NOT EXISTS public.scans (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  member_id      uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  partner_id     uuid NOT NULL REFERENCES public.partners(id) ON DELETE CASCADE,
  points_earned  integer NOT NULL DEFAULT 10,
  is_first_visit boolean NOT NULL DEFAULT false,
  created_at     timestamptz NOT NULL DEFAULT now()
);

-- Weekly 2x-multiplier tracker (3+ unique partners Mon–Sun = 2x points).
CREATE TABLE IF NOT EXISTS public.weekly_activity (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  member_id  uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  week_start date NOT NULL,
  partner_id uuid NOT NULL REFERENCES public.partners(id) ON DELETE CASCADE,
  scan_count integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (member_id, week_start, partner_id)
);

-- The rewards catalog members see on /streetpass/rewards (ordered by sort_order).
CREATE TABLE IF NOT EXISTS public.rewards (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  partner_id      uuid NOT NULL REFERENCES public.partners(id) ON DELETE CASCADE,
  name            text NOT NULL,
  description     text,
  points_required integer NOT NULL,
  max_per_month   integer NOT NULL DEFAULT 1,
  active          boolean NOT NULL DEFAULT true,
  sort_order      integer NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now()
);

-- A member spending points. code + expires_at are auto-generated by the
-- trigger in section 4 (api/redeem.js inserts only member/reward/points).
CREATE TABLE IF NOT EXISTS public.redemptions (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  member_id    uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  reward_id    bigint NOT NULL REFERENCES public.rewards(id) ON DELETE CASCADE,
  points_used  integer NOT NULL DEFAULT 0,
  code         text UNIQUE,
  status       text NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending','confirmed','expired','cancelled')),
  expires_at   timestamptz,
  confirmed_at timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Simple pageview counter, written by the anon client on every route change
-- (index.html trackPageview). Public read/write is intentional.
CREATE TABLE IF NOT EXISTS public.daily_stats (
  day       date NOT NULL,
  path      text NOT NULL,
  views     bigint NOT NULL DEFAULT 0,
  referrers bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (day, path)
);

