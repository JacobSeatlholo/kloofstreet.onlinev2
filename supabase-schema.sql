-- 4a. Redemption codes: generate the counter code + expiry automatically.
--     The API inserts {member_id, reward_id, points_used} and reads back
--     code/status/expires_at — the database must supply them.
CREATE OR REPLACE FUNCTION public.make_redemption_code()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.code IS NULL OR NEW.code = '' THEN
    NEW.code := 'KS-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
  END IF;
  IF NEW.expires_at IS NULL THEN
    NEW.expires_at := now() + interval '48 hours';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_redemption_code ON public.redemptions;
CREATE TRIGGER trg_redemption_code
  BEFORE INSERT ON public.redemptions
  FOR EACH ROW EXECUTE FUNCTION public.make_redemption_code();

-- 4b. Referral codes: every member needs one — the merchant workstation's
--     manual check-in looks members up by referral code. Auto-generate when
--     the signup flow didn't set one.
CREATE OR REPLACE FUNCTION public.make_referral_code()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.referral_code IS NULL OR NEW.referral_code = '' THEN
    NEW.referral_code :=
      upper(coalesce(nullif(left(regexp_replace(coalesce(NEW.display_name,''), '[^A-Za-z]', '', 'g'), 4), ''), 'MEM'))
      || '-' || lpad((floor(random() * 9000) + 1000)::text, 4);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_referral_code ON public.profiles;
CREATE TRIGGER trg_referral_code
  BEFORE INSERT ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.make_referral_code();

-- Backfill any existing members that pre-date the trigger.
UPDATE public.profiles SET referral_code = upper(coalesce(nullif(left(regexp_replace(coalesce(display_name,''), '[^A-Za-z]', '', 'g'), 4), ''), 'MEM')) || '-' || lpad((floor(random() * 9000) + 1000)::text, 4)
WHERE referral_code IS NULL OR referral_code = '';


-- ─────────────────────────────────────────────────────────────────────
-- 5. ROW LEVEL SECURITY
--
-- The anon key ships in streetpass-config.js (safe — that's the design).
-- These policies define exactly what the anon/browser client may do; the
-- Vercel functions use the service-role key and bypass RLS entirely.
--
--   table            anon (browser) may…                     everyone else
--   ───────────────  ──────────────────────────────────────  ─────────────
--   profiles         read/insert/update OWN row (auth.uid)   service-role only
--   rewards          read ACTIVE rewards (the catalog)       service-role only
--   redemptions      read OWN codes                          service-role only
--   daily_stats      read + upsert (public view counter)     service-role only
--   scans            nothing (all via /api/scan)             service-role only
--   weekly_activity  nothing                                 service-role only
--   partners         nothing                                 service-role only
-- ─────────────────────────────────────────────────────────────────────

ALTER TABLE public.profiles       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.partners       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scans          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.weekly_activity ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rewards        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.redemptions    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_stats    ENABLE ROW LEVEL SECURITY;

-- profiles: members see and edit only their own row
DROP POLICY IF EXISTS profiles_select_own ON public.profiles;
CREATE POLICY profiles_select_own ON public.profiles
  FOR SELECT TO anon, authenticated USING (auth.uid() = id);

DROP POLICY IF EXISTS profiles_insert_own ON public.profiles;
CREATE POLICY profiles_insert_own ON public.profiles
  FOR INSERT TO anon, authenticated WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS profiles_update_own ON public.profiles;
CREATE POLICY profiles_update_own ON public.profiles
  FOR UPDATE TO anon, authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

-- rewards: the public catalog (active rows only)
DROP POLICY IF EXISTS rewards_public_read_active ON public.rewards;
CREATE POLICY rewards_public_read_active ON public.rewards
  FOR SELECT TO anon, authenticated USING (active = true);

-- redemptions: members see their own codes (creation + confirmation happen
-- through the API with the service-role key)
DROP POLICY IF EXISTS redemptions_select_own ON public.redemptions;
CREATE POLICY redemptions_select_own ON public.redemptions
  FOR SELECT TO anon, authenticated USING (auth.uid() = member_id);

-- daily_stats: public pageview counter (select + upsert from the browser)
DROP POLICY IF EXISTS daily_stats_public_read ON public.daily_stats;
CREATE POLICY daily_stats_public_read ON public.daily_stats
  FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS daily_stats_public_insert ON public.daily_stats;
CREATE POLICY daily_stats_public_insert ON public.daily_stats
  FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS daily_stats_public_update ON public.daily_stats;
CREATE POLICY daily_stats_public_update ON public.daily_stats
  FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

-- scans / weekly_activity / partners: NO policies — fully locked.
-- Only the Vercel functions (service-role key) touch them.


